/* =============================================================================
 * SimEarth 2.0 — pack the city blocks into the civ atlas and write it out
 * -----------------------------------------------------------------------------
 * Shared by the CLI (tools/civ-atlas.js) and tests/civart.test.js, which
 * rebuilds the atlas in memory to prove the committed one matches the recipes.
 * The manifest carries what the map needs without decoding pixels: each
 * sprite's foot, its ground footprint and its silhouette per row (the layout
 * keeps every block visible behind the ones in front of it).
 * ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const C = require('./catalog');
const P = require('../terrain/palette');

const ROOT = path.join(__dirname, '..', '..');
const ATLAS_WIDTH = 128;

/** Shelf packing, tallest first; sets item.x/y and returns the atlas size. */
function pack(items) {
  const order = [...items].sort((a, b) => b.tex.h - a.tex.h || b.tex.w - a.tex.w || (a.key < b.key ? -1 : 1));
  let x = 0;
  let y = 0;
  let shelf = 0;
  for (const it of order) {
    if (x + it.tex.w > ATLAS_WIDTH) { x = 0; y += shelf; shelf = 0; }
    it.x = x;
    it.y = y;
    x += it.tex.w;
    shelf = Math.max(shelf, it.tex.h);
  }
  return { w: ATLAS_WIDTH, h: Math.ceil((y + shelf) / 8) * 8 };
}

/** Opaque columns per row, flat [left, right, …]; an empty row is [w, -1]. */
function spans(t) {
  const out = [];
  for (let y = 0; y < t.h; y++) {
    let l = t.w;
    let r = -1;
    for (let x = 0; x < t.w; x++) if (t.get(x, y) !== 0) { l = Math.min(l, x); r = x; }
    out.push(l, r);
  }
  return out;
}

/** Columns of the ground footprint: the bottom `depth` rows. */
function base(t, depth) {
  let l = t.w;
  let r = -1;
  for (let y = Math.max(0, t.h - depth); y < t.h; y++) {
    for (let x = 0; x < t.w; x++) if (t.get(x, y) !== 0) { l = Math.min(l, x); r = Math.max(r, x); }
  }
  return [l, r];
}

/** Pack a build into atlas pixels and the manifest. */
function assemble(art) {
  const items = [];
  const blocks = {};
  for (const b of C.BLOCKS) {
    const vars = art.blocks[b.id];
    if (!vars) continue;
    blocks[b.id] = { b, vars: vars.map((v, n) => { const it = { key: `${b.id}:${n}`, tex: v.tex, v }; items.push(it); return it; }) };
  }
  const size = pack(items);
  const px = new Uint8Array(size.w * size.h);
  for (const it of items) {
    for (let y = 0; y < it.tex.h; y++) {
      for (let x = 0; x < it.tex.w; x++) px[(it.y + y) * size.w + it.x + x] = it.tex.px[y * it.tex.w + x];
    }
  }
  const manifest = {
    version: 1,
    width: size.w,
    height: size.h,
    box: C.BOX,
    shadow: C.SHADOW,
    eras: C.ERAS,
    tribeColors: C.TRIBE_COLORS.map((t) => ({ ...t, rgb: P.PALETTE[P.c(t.pixel)].slice(0, 3) })),
    blocks: Object.fromEntries(Object.values(blocks).map(({ b, vars }) => [b.id, {
      name: b.name, era: b.era, role: b.role, depth: b.depth,
      variants: vars.map((it) => {
        const [bx0, bx1] = base(it.tex, b.depth);
        return {
          rect: { x: it.x, y: it.y, w: it.tex.w, h: it.tex.h },
          ax: Math.floor(it.tex.w / 2), ay: it.tex.h - 1, size: it.v.size || '',
          bx0, bx1, spans: spans(it.tex),
          ...(it.tex.smoke && it.tex.smoke.length ? { smoke: [...it.tex.smoke] } : {}),
        };
      }),
    }])),
  };
  return { px, size, manifest };
}

const TS_HEADER = `/* =============================================================================
 * SimEarth 2.0 — city atlas (GENERATED by tools/civ-atlas.js — do not edit)
 * -----------------------------------------------------------------------------
 * The city building blocks as one indexed PNG in the terrain palette (data
 * URI: no fetch, no tainted canvas over file://) and the manifest that says
 * where each block is, where it stands and how much ground it covers.
 * Contract and ids: tools/civ/catalog.js · spec: docs/zivilisation-spec.md §3.
 * ========================================================================== */

namespace SE {
  export interface CivRect { readonly x: number; readonly y: number; readonly w: number; readonly h: number }
  /** One drawing of a block; (ax, ay) is its foot inside rect. */
  export interface CivSprite {
    readonly rect: CivRect; readonly ax: number; readonly ay: number;
    /** 's' | 'm' | 'l' for dwellings, else ''. */
    readonly size: string;
    /** Columns bx0..bx1 of rect that the bottom \`depth\` rows (the ground footprint) cover. */
    readonly bx0: number; readonly bx1: number;
    /** Opaque columns per row of rect, [left, right, …]; left > right for an empty row. */
    readonly spans: readonly number[];
    /** Chimney openings of the sprite, x, y pairs in rect pixels: smoke rises one row above each. */
    readonly smoke?: readonly number[];
  }
  export interface CivBlock {
    readonly name: string; readonly era: string | null; readonly role: string;
    /** Rows of the ground footprint. */
    readonly depth: number;
    readonly variants: readonly CivSprite[];
  }
  /** A tribe colour: terrain palette name of the pixel banner, ART_PALETTE key of the SVG banner. */
  export interface CivTribeColor {
    readonly id: string; readonly name: string; readonly pixel: string; readonly art: string; readonly rgb: readonly number[];
  }
  export interface CivManifest {
    readonly version: number; readonly width: number; readonly height: number;
    /** The box a city stays in: its tile and up to box.h - 16 px above. */
    readonly box: { readonly w: number; readonly h: number };
    /** Drop shadow under each block (tools/civ/catalog.js SHADOW). */
    readonly shadow: { readonly rgb: readonly number[]; readonly alpha: number; readonly width: number; readonly ry: number };
    /** Era ids from Tech.Stone on. */
    readonly eras: readonly string[];
    readonly tribeColors: readonly CivTribeColor[];
    readonly blocks: Readonly<Record<string, CivBlock>>;
  }
`;

/** The generated TypeScript source for the atlas and its manifest. */
function renderTs(png, manifest) {
  return `${TS_HEADER}
  export const CIV_MANIFEST: CivManifest = ${JSON.stringify(manifest)};

  export const CIV_ATLAS_PNG = 'data:image/png;base64,${png.toString('base64')}';
}
`;
}

function writeOutputs(png, manifest) {
  const dir = path.join(ROOT, 'assets', 'civ');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'atlas.png'), png);
  fs.writeFileSync(path.join(ROOT, 'src', 'civatlas.ts'), renderTs(png, manifest));
  console.log(`wrote assets/civ/atlas.png (${manifest.width}×${manifest.height}, ${(png.length / 1024).toFixed(1)} KB), src/civatlas.ts`);
}

module.exports = { assemble, renderTs, writeOutputs };
