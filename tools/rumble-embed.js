/* Embeds assets/audio/sfx/rumble-bass.mp3 as base64 into src/rumblebass.ts.
 * WebAudio cannot fetch() it over file://, and an <audio> element's volume
 * steps crackle when faded: the decoded buffer fades sample-exact.
 * Run after changing the MP3: node tools/rumble-embed.js && npm run build */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const b64 = fs.readFileSync(path.join(root, 'assets/audio/sfx/rumble-bass.mp3')).toString('base64');
fs.writeFileSync(path.join(root, 'src/rumblebass.ts'),
  `/* Generated by tools/rumble-embed.js from assets/audio/sfx/rumble-bass.mp3 — do not edit. */\n` +
  `namespace SE {\n  export const RUMBLE_BASS_MP3 = '${b64}';\n}\n`);
