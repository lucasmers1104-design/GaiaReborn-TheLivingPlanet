/* =============================================================================
 * Gaia Reborn — pack the living-interface frames into the UI atlas
 * -----------------------------------------------------------------------------
 * Shared by the CLI (tools/ui-atlas.js), the agents' bundles
 * (tools/ui-bundle.js) and tests/uiatlas.test.js, which rebuilds the atlas
 * in memory to prove the committed one matches the recipes. Frames are
 * shelf-packed one by one (tallest first, a sprite's frames in order), so a
 * long animation wraps instead of widening the atlas; the manifest gives
 * every frame its own rect.
 * ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const C = require('./catalog');
const P = require('./palette');
const { anchorOf } = require('./build');

const ROOT = path.join(__dirname, '..', '..');
const ATLAS_WIDTH = 512;

/** Shelf packing, tallest first; sets item.x/y, returns the atlas size. */
function pack(items) {
  const width = Math.max(ATLAS_WIDTH, ...items.map((it) => it.w));
  const order = [...items].sort((a, b) => b.h - a.h || b.w - a.w || a.order - b.order);
  let x = 0;
  let y = 0;
  let shelf = 0;
  for (const it of order) {
    if (x + it.w > width) { x = 0; y += shelf; shelf = 0; }
    it.x = x;
    it.y = y;
    x += it.w;
    shelf = Math.max(shelf, it.h);
  }
  return { w: width, h: Math.max(1, y + shelf) };
}

/** art = build(…) → { px (palette indices), size, manifest } */
function assemble(art) {
  const built = C.SPRITES.filter((s) => art.sprites[s.id]);
  const items = [];
  const byId = {};
  for (const s of built) {
    byId[s.id] = art.sprites[s.id].map((t) => {
      const it = { t, w: t.w, h: t.h, order: items.length };
      items.push(it);
      return it;
    });
  }
  const size = pack(items);
  const px = new Uint8Array(size.w * size.h);
  for (const { t, x, y } of items) {
    for (let r = 0; r < t.h; r++) px.set(t.px.subarray(r * t.w, (r + 1) * t.w), (y + r) * size.w + x);
  }
  const manifest = {
    version: 1,
    width: size.w,
    height: size.h,
    sprites: Object.fromEntries(built.map((s) => {
      const [ax, ay] = anchorOf(s);
      return [s.id, {
        name: s.name, w: s.w, h: s.h, fps: s.fps, loop: s.loop ?? s.frames, ax, ay, anchor: s.anchor,
        points: s.points ?? {}, layout: s.layout ?? null, placeholder: !!art.placeholder[s.id],
        frames: byId[s.id].map((it) => ({ x: it.x, y: it.y, w: it.w, h: it.h })),
      }];
    })),
    colors: Object.fromEntries(Object.entries(P.INDEX).map(([name, i]) => [name, P.hex(i)])),
  };
  return { px, size, manifest };
}

const TS_HEADER = `/* =============================================================================
 * Gaia Reborn — living-interface atlas (GENERATED by tools/ui-atlas.js — do not edit)
 * -----------------------------------------------------------------------------
 * Every pixel sprite of the living interface as one indexed PNG in the UI
 * palette (data URI: no fetch, no tainted canvas over file://), and the
 * manifest: where each frame is, its anchor and named points, and every
 * palette colour by name. Contract and ids: tools/uiart/catalog.js; drawn by
 * src/uiart.ts.
 * ========================================================================== */

namespace SE {
  export interface UiRect { readonly x: number; readonly y: number; readonly w: number; readonly h: number }
  export interface UiSprite {
    readonly name: string; readonly w: number; readonly h: number; readonly fps: number; readonly loop: number;
    readonly ax: number; readonly ay: number; readonly anchor: 'foot' | 'center' | 'topleft';
    readonly points: Readonly<Record<string, readonly [number, number]>>; readonly layout: string | null;
    readonly placeholder: boolean; readonly frames: readonly UiRect[];
  }
  export interface UiManifest {
    readonly version: number; readonly width: number; readonly height: number;
    readonly sprites: Readonly<Record<string, UiSprite>>; readonly colors: Readonly<Record<string, string>>;
  }
`;

function renderTs(png, manifest) {
  return `${TS_HEADER}  export const UI_MANIFEST: UiManifest = ${JSON.stringify(manifest)};
  export const UI_ATLAS_PNG = 'data:image/png;base64,${png.toString('base64')}';
}
`;
}

/** Into the repository (assets/uiart/atlas.png, src/uiatlas.ts), or with `dir` both files into that folder. */
function writeOutputs(png, manifest, dir = null) {
  const pngDir = dir ?? path.join(ROOT, 'assets', 'uiart');
  const tsFile = dir ? path.join(dir, 'uiatlas.ts') : path.join(ROOT, 'src', 'uiatlas.ts');
  fs.mkdirSync(pngDir, { recursive: true });
  fs.writeFileSync(path.join(pngDir, 'atlas.png'), png);
  fs.writeFileSync(tsFile, renderTs(png, manifest));
  console.log(`wrote ${path.join(pngDir, 'atlas.png')} (${manifest.width}×${manifest.height}, ${(png.length / 1024).toFixed(1)} KB), ${tsFile}`);
}

module.exports = { assemble, renderTs, writeOutputs };
